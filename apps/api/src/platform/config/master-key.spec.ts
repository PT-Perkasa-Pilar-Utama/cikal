import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, expect, it } from "vitest";
import { loadConfig } from "./config.js";

const dir = mkdtempSync(join(tmpdir(), "cikal-master-key-"));
const secret = join(dir, "secret");
writeFileSync(secret, "test-secret");
const env = {
  APP_ENV: "test",
  DATABASE_URL: "postgres://test:test@localhost/test",
  S3_ENDPOINT: "http://localhost:9000",
  S3_REGION: "us-east-1",
  S3_BUCKET: "test",
  S3_ACCESS_KEY_FILE: secret,
  S3_SECRET_KEY_FILE: secret,
  MONITORING_TOKEN_FILE: secret,
  ALLOW_SIMULATION_ADAPTERS: "true",
};
afterAll(() => rmSync(dir, { recursive: true, force: true }));

it("TL-S3-05 rejects an unreadable master key without exposing filesystem details", () => {
  expect(() => loadConfig({ ...env, MASTER_KEY_FILE: join(dir, "missing") })).toThrow(
    "MASTER_KEY_FILE must reference a readable file",
  );
});

it.each(["", "not-base64", Buffer.alloc(31).toString("base64"), Buffer.alloc(33).toString("base64")])(
  "TL-S3-05 rejects malformed master key %s",
  (encoded) => {
    const path = join(dir, "invalid");
    writeFileSync(path, encoded);
    expect(() => loadConfig({ ...env, MASTER_KEY_FILE: path })).toThrow(
      "MASTER_KEY_FILE must contain a Base64-encoded 32-byte key",
    );
  },
);

it("TL-S3-05 reads the 32-byte master key generated by the deployment runbook", () => {
  const path = join(dir, "valid");
  const bytes = Buffer.from("0123456789abcdef0123456789abcdef");
  writeFileSync(path, `${bytes.toString("base64")}\n`);
  expect(loadConfig({ ...env, MASTER_KEY_FILE: path }).masterKey).toEqual(bytes);
});
